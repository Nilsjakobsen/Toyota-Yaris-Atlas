// Writes blender/component-ids.json from src/data/components.ts so the Blender script can
// validate object names without parsing TypeScript. Run after adding or renaming components:
//   npm run gen:ids
// (Node 22.18+/24 strips TypeScript types natively; components.ts has only type imports.)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const { COMPONENTS } = await import("../src/data/components.ts");

const out = {
  _comment: "Generated by tools/gen-component-ids.mjs — do not edit by hand. Object names in Blender must match these IDs.",
  units: "metres",
  axes: { up: "+Y (glTF) / +Z (Blender)", forward: "+Z (glTF) / -Y (Blender)", left: "+X in both" },
  components: COMPONENTS.map((c) => ({
    id: c.id,
    name: c.name.en,
    system: c.system,
    sides: !!c.sides,
    location: c.location.status,
  })),
};

const target = fileURLToPath(new URL("../blender/component-ids.json", import.meta.url));
writeFileSync(target, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${out.components.length} component IDs to blender/component-ids.json`);
