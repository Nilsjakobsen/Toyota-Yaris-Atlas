"""
Yaris Atlas — Blender helper (tested with Blender 5.2 LTS).

What it does
  * Import  : loads the app's placeholder GLB (About → "Download placeholder GLB") and
              sorts the parts into one collection per system under "YarisAtlas".
  * Validate: checks names/IDs against blender/component-ids.json, units, scale,
              duplicates and objects below the ground; makes sure every component
              object carries an `atlas_id` custom property.
  * Export  : writes the "YarisAtlas" collection to a GLB with the settings the app
              expects (+Y up, custom properties as extras, modifiers applied).

How to use it in Blender (no add-on install needed)
  1. Open the Scripting workspace → Text → Open… → choose this file → Run Script.
  2. In the 3D Viewport press N and open the "Yaris Atlas" tab.

Command line (Blender does not need to be open):
  blender --background --python blender/yaris_atlas_tools.py -- \
      --import path/to/yaris-atlas-placeholders.glb --validate \
      --export public/models/yaris-atlas.glb

Conventions (see docs/BLENDER-GLB-WORKFLOW.md)
  * 1 Blender unit = 1 metre. Car front faces -Y in Blender (+Z in the app), up is +Z
    in Blender (+Y in the app), the car's LEFT side is +X in both.
  * Each component is ONE top-level object (an Empty or a mesh) named exactly like its
    ID, e.g. "battery". Meshes go underneath it. Blender's ".001" suffix is tolerated.
  * Sided components (wheels, brakes, struts, drive shafts) have two child objects,
    "<id>_L" (+X) and "<id>_R" (−X); each explodes outward on its own.
  * Materials named "atlas-<name>" (e.g. "atlas-paint-silver") are replaced by the app's
    built-in material of that name; any other material is used as exported.
"""

import json
import os
import sys

import bpy

ROOT_COLLECTION = "YarisAtlas"
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__)) if "__file__" in globals() and os.path.isfile(__file__) else ""
REPO_DIR = os.path.dirname(SCRIPT_DIR) if SCRIPT_DIR else ""


# --------------------------------------------------------------------------- helpers

def load_component_ids(path=None):
    """Read blender/component-ids.json (generated by `npm run gen:ids`)."""
    candidates = [path] if path else []
    if SCRIPT_DIR:
        candidates.append(os.path.join(SCRIPT_DIR, "component-ids.json"))
    for c in candidates:
        if c and os.path.isfile(c):
            with open(c, encoding="utf-8") as f:
                data = json.load(f)
            return {c["id"]: c for c in data["components"]}
    raise FileNotFoundError("component-ids.json not found — pass --ids or keep this script inside the repo's blender/ folder.")


def base_name(name):
    """'battery.001' -> 'battery'."""
    head, dot, tail = name.rpartition(".")
    return head if dot and tail.isdigit() and len(tail) == 3 else name


def component_id_of(obj, known):
    for raw in (obj.get("atlas_id"), obj.name):
        if isinstance(raw, str):
            n = base_name(raw.strip()).lower()
            if n in known:
                return n
    return None


def ensure_collection(name, parent=None):
    coll = bpy.data.collections.get(name)
    if coll is None:
        coll = bpy.data.collections.new(name)
    parent = parent or bpy.context.scene.collection
    if coll.name not in [c.name for c in parent.children]:
        parent.children.link(coll)
    return coll


def move_hierarchy(obj, target):
    """Link obj and all its descendants to `target` only."""
    for o in [obj] + list(obj.children_recursive):
        for c in list(o.users_collection):
            if c != target:
                c.objects.unlink(o)
        if target not in o.users_collection:
            target.objects.link(o)


def atlas_root_objects(known):
    """Top-most objects in the YarisAtlas collection tree that stand for a component."""
    root = bpy.data.collections.get(ROOT_COLLECTION)
    if root is None:
        return []
    objs = list(root.all_objects)
    result = []
    for o in objs:
        if component_id_of(o, known) is None:
            continue
        p, inside = o.parent, False
        while p is not None:
            if component_id_of(p, known):
                inside = True
                break
            p = p.parent
        if not inside:
            result.append(o)
    return result


# --------------------------------------------------------------------------- actions

def import_placeholders(glb_path, ids_path=None):
    known = load_component_ids(ids_path)
    before = set(bpy.data.objects)
    bpy.ops.import_scene.gltf(filepath=glb_path)
    new = [o for o in bpy.data.objects if o not in before]

    root = ensure_collection(ROOT_COLLECTION)
    system_colls = {}
    for o in new:
        cid = component_id_of(o, known)
        if cid is None or (o.parent and component_id_of(o.parent, known)):
            continue
        system = known[cid]["system"]
        coll = system_colls.get(system) or ensure_collection(f"{ROOT_COLLECTION}.{system}", root)
        system_colls[system] = coll
        o["atlas_id"] = cid
        if o.parent and o.parent.name.startswith(ROOT_COLLECTION):
            mw = o.matrix_world.copy()  # keep the assembled position when un-parenting
            o.parent = None
            o.matrix_world = mw
        move_hierarchy(o, coll)
    # The exporter's wrapper empty ("YarisAtlas") is not needed inside Blender.
    for o in new:
        if o.name.startswith(ROOT_COLLECTION) and o.type == "EMPTY" and not o.children:
            bpy.data.objects.remove(o)
    print(f"[yaris-atlas] imported {len(new)} objects into collection '{ROOT_COLLECTION}'")


def validate(ids_path=None, fix=True):
    """Return a list of (level, message). level is 'ok', 'warn' or 'error'."""
    known = load_component_ids(ids_path)
    report = []
    scene = bpy.context.scene
    us = scene.unit_settings
    if us.system != "METRIC" or abs(us.scale_length - 1.0) > 1e-6:
        report.append(("error", f"Scene units must be Metric with Unit Scale 1.0 (now {us.system}, {us.scale_length})."))
    root = bpy.data.collections.get(ROOT_COLLECTION)
    if root is None:
        report.append(("error", f"No '{ROOT_COLLECTION}' collection. Put your component objects in it (or use Import first)."))
        return report

    roots = atlas_root_objects(known)
    seen = {}
    for o in roots:
        cid = component_id_of(o, known)
        if cid in seen:
            report.append(("warn", f"'{o.name}' duplicates component '{cid}' (already '{seen[cid]}'); the app uses the first one it finds."))
            continue
        seen[cid] = o.name
        if fix and o.get("atlas_id") != cid:
            o["atlas_id"] = cid
        if known[cid].get("sides"):
            kids = [c.name for c in o.children]
            if not any(k.endswith("_L") or ".L" in k for k in kids) or not any(k.endswith("_R") or ".R" in k for k in kids):
                report.append(("warn", f"'{cid}' should have two children named '{cid}_L' and '{cid}_R' so each side explodes separately."))
        meshes = [c for c in [o] + list(o.children_recursive) if c.type == "MESH"]
        if not meshes:
            report.append(("warn", f"'{cid}' has no mesh — the app will keep its built-in placeholder."))
        for m in meshes:
            if any(s < 0 for s in m.matrix_world.to_scale()):
                report.append(("warn", f"'{m.name}' has a negative scale; apply it (Ctrl+A → Scale) to avoid flipped normals."))
            zmin = min((m.matrix_world @ v.co).z for v in m.data.vertices) if m.data.vertices else 0
            if zmin < -0.005:
                report.append(("warn", f"'{m.name}' goes {abs(zmin) * 1000:.0f} mm below the ground (Z=0)."))

    for o in root.all_objects:
        if o.parent is None and component_id_of(o, known) is None and o.type in {"MESH", "EMPTY"}:
            report.append(("warn", f"'{o.name}' is not a component ID and will be ignored by the app."))

    missing = [i for i in known if i not in seen]
    report.append(("ok", f"{len(seen)} of {len(known)} components present."))
    if missing:
        report.append(("ok", "Missing (the app will use placeholders): " + ", ".join(missing)))
    return report


def export_glb(path):
    root = bpy.data.collections.get(ROOT_COLLECTION)
    if root is None:
        raise RuntimeError(f"No '{ROOT_COLLECTION}' collection to export.")
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    bpy.ops.export_scene.gltf(
        filepath=path,
        export_format="GLB",
        collection=ROOT_COLLECTION,
        export_extras=True,  # custom properties such as atlas_id travel as glTF extras
        export_yup=True,  # Blender Z-up → glTF/three.js Y-up
        export_apply=True,  # apply modifiers so what you see is what ships
        export_cameras=False,
        export_lights=False,
        export_animations=False,
        export_draco_mesh_compression_enable=False,  # the app does not ship a Draco decoder
    )
    print(f"[yaris-atlas] exported '{ROOT_COLLECTION}' to {path}")


def print_report(report):
    for level, msg in report:
        print(f"[yaris-atlas] {level.upper():5} {msg}")


# --------------------------------------------------------------------------- UI panel

def default_export_path():
    return os.path.join(REPO_DIR, "public", "models", "yaris-atlas.glb") if REPO_DIR else ""


class YARIS_OT_import(bpy.types.Operator):
    bl_idname = "yaris_atlas.import_placeholders"
    bl_label = "Import placeholder GLB"
    filepath: bpy.props.StringProperty(subtype="FILE_PATH")
    filter_glob: bpy.props.StringProperty(default="*.glb;*.gltf", options={"HIDDEN"})

    def invoke(self, context, event):
        context.window_manager.fileselect_add(self)
        return {"RUNNING_MODAL"}

    def execute(self, context):
        import_placeholders(self.filepath)
        return {"FINISHED"}


class YARIS_OT_validate(bpy.types.Operator):
    bl_idname = "yaris_atlas.validate"
    bl_label = "Validate"

    def execute(self, context):
        report = validate()
        print_report(report)
        worst = "ERROR" if any(l == "error" for l, _ in report) else "WARNING" if any(l == "warn" for l, _ in report) else "INFO"
        for level, msg in report[:12]:
            self.report({"ERROR" if level == "error" else "WARNING" if level == "warn" else "INFO"}, msg)
        self.report({worst}, "Validation finished — see the Info editor or system console for all lines.")
        return {"FINISHED"}


class YARIS_OT_export(bpy.types.Operator):
    bl_idname = "yaris_atlas.export"
    bl_label = "Export GLB for the app"
    filepath: bpy.props.StringProperty(subtype="FILE_PATH")
    filter_glob: bpy.props.StringProperty(default="*.glb", options={"HIDDEN"})

    def invoke(self, context, event):
        self.filepath = default_export_path() or "yaris-atlas.glb"
        context.window_manager.fileselect_add(self)
        return {"RUNNING_MODAL"}

    def execute(self, context):
        print_report(validate())
        export_glb(self.filepath)
        self.report({"INFO"}, f"Exported to {self.filepath}")
        return {"FINISHED"}


class YARIS_PT_panel(bpy.types.Panel):
    bl_label = "Yaris Atlas"
    bl_idname = "YARIS_PT_panel"
    bl_space_type = "VIEW_3D"
    bl_region_type = "UI"
    bl_category = "Yaris Atlas"

    def draw(self, context):
        col = self.layout.column(align=True)
        col.operator(YARIS_OT_import.bl_idname, icon="IMPORT")
        col.operator(YARIS_OT_validate.bl_idname, icon="CHECKMARK")
        col.operator(YARIS_OT_export.bl_idname, icon="EXPORT")
        self.layout.label(text="1 unit = 1 m · front = −Y · left = +X")


CLASSES = (YARIS_OT_import, YARIS_OT_validate, YARIS_OT_export, YARIS_PT_panel)


def register():
    for c in CLASSES:
        try:
            bpy.utils.unregister_class(c)
        except RuntimeError:
            pass
        bpy.utils.register_class(c)


# --------------------------------------------------------------------------- entry point

def main(argv):
    import argparse

    p = argparse.ArgumentParser(prog="yaris_atlas_tools.py")
    p.add_argument("--import", dest="import_path")
    p.add_argument("--validate", action="store_true")
    p.add_argument("--export", dest="export_path")
    p.add_argument("--ids", dest="ids_path")
    p.add_argument("--fail-on-warn", action="store_true")
    args = p.parse_args(argv)

    if args.import_path:
        import_placeholders(args.import_path, args.ids_path)
    status = 0
    if args.validate or args.export_path:
        report = validate(args.ids_path)
        print_report(report)
        if any(l == "error" for l, _ in report) or (args.fail_on_warn and any(l == "warn" for l, _ in report)):
            status = 1
    if args.export_path and status == 0:
        export_glb(args.export_path)
    return status


if __name__ == "__main__":
    if "--" in sys.argv:
        code = main(sys.argv[sys.argv.index("--") + 1:])
        if bpy.app.background:
            sys.exit(code)
    else:
        register()
        print("[yaris-atlas] panel registered: 3D Viewport → N → 'Yaris Atlas'")
